SET NAMES utf8mb4;
SET time_zone = '+07:00';
CREATE TABLE roles (
 id TINYINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(30) NOT NULL UNIQUE,
 label VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE staff (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 role_id TINYINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (role_id) REFERENCES roles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE users (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL DEFAULT '',
 password_hash VARCHAR(255) NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE addresses (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL,
 recipient VARCHAR(120) NOT NULL,
 phone VARCHAR(20) NOT NULL,
 address_line VARCHAR(500) NOT NULL,
 is_default BOOLEAN NOT NULL DEFAULT 0,
 default_owner BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN is_default = 1 THEN user_id ELSE NULL END) STORED,
 UNIQUE KEY uq_default_address(default_owner),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE categories (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(100) NOT NULL UNIQUE,
 slug VARCHAR(120) NOT NULL UNIQUE,
 description TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE brands (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(100) NOT NULL UNIQUE,
 slug VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE products (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 category_id BIGINT UNSIGNED NOT NULL,
 brand_id BIGINT UNSIGNED NOT NULL,
 sku VARCHAR(60) NOT NULL UNIQUE,
 name VARCHAR(200) NOT NULL,
 slug VARCHAR(220) NOT NULL UNIQUE,
 description TEXT NOT NULL,
 price DECIMAL(15,0) NOT NULL CHECK(price >= 0),
 stock INT UNSIGNED NOT NULL DEFAULT 0,
 min_stock INT UNSIGNED NOT NULL DEFAULT 5,
 is_featured BOOLEAN NOT NULL DEFAULT 0,
 is_active BOOLEAN NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES categories(id),
 FOREIGN KEY (brand_id) REFERENCES brands(id),
 KEY idx_catalog(category_id,is_active,price),
 KEY idx_brand(brand_id,is_active),
 KEY idx_newest(is_active,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE product_images (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 product_id BIGINT UNSIGNED NOT NULL,
 path VARCHAR(255) NOT NULL,
 sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE product_specs (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 product_id BIGINT UNSIGNED NOT NULL,
 spec_key VARCHAR(100) NOT NULL,
 spec_value VARCHAR(500) NOT NULL,
 sort_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 UNIQUE KEY uq_spec(product_id,spec_key),
 FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE orders (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 code VARCHAR(40) NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 checkout_token CHAR(64) NOT NULL UNIQUE,
 status ENUM('pending','processing','shipping','completed','cancelled') NOT NULL DEFAULT 'pending',
 recipient VARCHAR(120) NOT NULL,
 phone VARCHAR(20) NOT NULL,
 address_line VARCHAR(500) NOT NULL,
 note VARCHAR(1000) NOT NULL DEFAULT '',
 payment_method ENUM('cod','bank_transfer') NOT NULL,
 total DECIMAL(15,0) NOT NULL CHECK(total >= 0),
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 KEY idx_user_orders(user_id,created_at),
 KEY idx_order_status_date(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE order_items (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 product_name VARCHAR(200) NOT NULL,
 sku VARCHAR(60) NOT NULL,
 unit_price DECIMAL(15,0) NOT NULL CHECK(unit_price >= 0),
 quantity INT UNSIGNED NOT NULL CHECK(quantity > 0),
 UNIQUE KEY uq_order_product(order_id,product_id),
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE order_status_history (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT UNSIGNED NOT NULL,
 staff_id BIGINT UNSIGNED NULL,
 from_status VARCHAR(20) NULL,
 to_status VARCHAR(20) NOT NULL,
 note VARCHAR(500) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (staff_id) REFERENCES staff(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE stock_movements (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 product_id BIGINT UNSIGNED NOT NULL,
 order_id BIGINT UNSIGNED NULL,
 staff_id BIGINT UNSIGNED NULL,
 type ENUM('opening','receipt','issue','sale','cancellation') NOT NULL,
 quantity INT NOT NULL CHECK(quantity <> 0),
 stock_after INT UNSIGNED NOT NULL,
 reason VARCHAR(500) NOT NULL,
 request_token CHAR(64) NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (product_id) REFERENCES products(id),
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (staff_id) REFERENCES staff(id),
 UNIQUE KEY uq_order_movement(order_id,product_id,type),
 KEY idx_stock_date(product_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE payments (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT UNSIGNED NOT NULL,
 staff_id BIGINT UNSIGNED NULL,
 amount DECIMAL(15,0) NOT NULL CHECK(amount > 0),
 method ENUM('cod','bank_transfer') NOT NULL,
 status ENUM('unpaid','paid','refunded') NOT NULL,
 transaction_code VARCHAR(120) NULL UNIQUE,
 request_token CHAR(64) NOT NULL UNIQUE,
 paid_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (staff_id) REFERENCES staff(id),
 KEY idx_payment_report(status,paid_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE invoices (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT UNSIGNED NOT NULL UNIQUE,
 code VARCHAR(40) NOT NULL UNIQUE,
 staff_id BIGINT UNSIGNED NULL,
 issued_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (staff_id) REFERENCES staff(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_notes (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT UNSIGNED NOT NULL,
 staff_id BIGINT UNSIGNED NOT NULL,
 note VARCHAR(2000) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (staff_id) REFERENCES staff(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE audit_logs (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
 staff_id BIGINT UNSIGNED NULL,
 action VARCHAR(100) NOT NULL,
 entity_type VARCHAR(50) NOT NULL,
 entity_id BIGINT UNSIGNED NULL,
 details TEXT NULL,
 ip_address VARCHAR(45) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (staff_id) REFERENCES staff(id),
 KEY idx_audit_date(created_at),
 KEY idx_audit_actor(staff_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE login_attempts (
 identity_hash CHAR(64) PRIMARY KEY,
 failures INT UNSIGNED NOT NULL DEFAULT 0,
 window_started_at DATETIME NOT NULL,
 blocked_until DATETIME NULL,
 KEY idx_attempt_expiry(window_started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
